package com.client.xvideos.x.feature.auth

/**
 * Этап входа в X: форма показывает его, пока вход идёт.
 *
 * Вход проходит через страницу сайта, и дольше всего длится проверка
 * устройства — капча сайта решается сама, без участия пользователя, но может
 * занять заметное время.
 *
 * @property text подпись этапа для формы входа.
 */
enum class XSignInStep(val text: String) {
    /** Загружается страница входа сайта. */
    OPENING("Открываю страницу входа…"),

    /** Страница сайта проверяет устройство: решает свою капчу. */
    CAPTCHA("Сайт проверяет устройство…"),

    /** Логин и пароль отправлены, ждём ответ сайта. */
    SENDING("Вход…"),
}
