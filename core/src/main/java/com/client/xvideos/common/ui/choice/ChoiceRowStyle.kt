package com.client.xvideos.common.ui.choice

/**
 * Стиль ряда выбора [ChoiceRow] — набор дизайн-системы. Стиль закрепляется за
 * экраном в коде; акцентный цвет задаёт экран (розовый L, свой у R и X).
 * Буквы — как в макетах, по которым выбирали стиль.
 */
enum class ChoiceRowStyle {
    /** Сегментные кнопки Material3 с галочкой у выбранной (прежний вид). */
    MATERIAL,

    /** A. Отдельные кнопки с контуром; выбранная — акцентный контур, подсветка и текст. */
    OUTLINE,

    /** B. Отдельные серые плашки; выбранная — сплошная акцентная, тёмный текст. */
    SOLID,

    /** C. Как вкладки: текст, у выбранной — акцентная полоса на всю ширину, линия под рядом. */
    TABS,

    /** D. Общая тёмная дорожка; выбранная — светлее, без акцента. */
    TRACK,

    /** E. Без рамок; выбранная — серая плашка и акцентная точка перед текстом. */
    DOT,

    /** F. Текст; у выбранной — белый текст и короткая акцентная черта под ним. */
    UNDERLINE,

    /** G. Общая тёмная дорожка; выбранная — серая с акцентным текстом. */
    TRACK_ACCENT,

    /** H. Кнопки с контуром; выбранная — светлая плашка с тёмным текстом. */
    INVERSE,
}
