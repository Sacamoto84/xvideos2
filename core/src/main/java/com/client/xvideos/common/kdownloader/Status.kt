package com.client.xvideos.common.kdownloader

/**
 * Статус жизненного цикла задачи загрузки в [KDownloader].
 *
 * Отражает текущую фазу обработки: от постановки в очередь до завершения или ошибки.
 * Вспомогательные свойства позволяют централизованно проверять состояние задачи без
 * прямого сравнения с константами перечисления.
 */
enum class Status {
    /** Задача ожидает выделения слота выполнения в пуле потоков. */
    QUEUED,

    /** Файл активно скачивается по сети. */
    RUNNING,

    /** Загрузка временно приостановлена пользователем или системой. */
    PAUSED,

    /** Загрузка успешно завершена, файл валидирован и перемещен в целевую директорию. */
    COMPLETED,

    /** Загрузка отменена пользователем, частичные данные удалены. */
    CANCELLED,

    /** Произошла ошибка сети, диска или валидации данных. */
    FAILED,

    /** Неизвестный или неинициализированный статус (резервный fallback). */
    UNKNOWN;

    /** Истина, если загрузка перешла в конечное состояние (успех, отмена или ошибка). */
    val isFinished: Boolean get() = this == COMPLETED || this == CANCELLED || this == FAILED

    /** Истина, если задача в данный момент активно скачивается. */
    val isRunning: Boolean get() = this == RUNNING

    /** Истина, если задача приостановлена. */
    val isPaused: Boolean get() = this == PAUSED

    /** Истина, если задача находится в очереди ожидания. */
    val isQueued: Boolean get() = this == QUEUED

    /** Истина, если файл успешно скачан и сохранен. */
    val isCompleted: Boolean get() = this == COMPLETED

    /** Истина, если загрузка прервалась ошибкой. */
    val isFailed: Boolean get() = this == FAILED

    /** Истина, если загрузка была явно отменена. */
    val isCancelled: Boolean get() = this == CANCELLED

    /** Истина, если задача требует ресурсов (в очереди или уже скачивается). */
    val isActive: Boolean get() = this == QUEUED || this == RUNNING

    /** Терминальное состояние, после которого задача не возобновляется автоматически. */
    val isTerminal: Boolean get() = isFinished
}
