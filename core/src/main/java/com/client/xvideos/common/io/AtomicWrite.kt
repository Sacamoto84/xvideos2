package com.client.xvideos.common.io

import java.io.File
import java.io.IOException

/**
 * Пишет текст во временный файл рядом и переименовывает его поверх целевого.
 *
 * Переименование в пределах одной ФС атомарно, поэтому читатель видит либо
 * старое содержимое целиком, либо новое целиком — но не обрывок. Обрезанный
 * JSON в хранилищах приложения не диагностируется: он молча отбрасывается на
 * чтении, и элемент просто исчезает из списка.
 *
 * Временный файл — со случайным именем: детерминированное `"$name.tmp"` делило
 * бы одну цель между двумя экземплярами хранилища, а лок операций принадлежит
 * экземпляру, а не пути. Хранилища подчищают остатки по суффиксу `.tmp`.
 *
 * Не атомарно только окно фолбэка ниже (delete цели + повторный rename) —
 * на некоторых ФС renameTo не перезаписывает существующий файл. Читатель в
 * этом окне видит отсутствие файла; окно закрыто локом вызывающего хранилища.
 * Синхронизации с носителем (fsync) перед переименованием нет: цена потери
 * при отключении питания — один элемент списка, и оба хранилища считают это
 * принятым ограничением.
 *
 * @throws IOException если записать файл не удалось.
 */
fun File.writeTextAtomically(text: String) {
    parentFile?.mkdirs()
    val temp = File.createTempFile("atomic-", ".tmp", parentFile)
    temp.writeText(text, Charsets.UTF_8)
    if (!temp.renameTo(this)) {
        // На некоторых ФС renameTo не перезаписывает существующий файл.
        delete()
        if (!temp.renameTo(this)) {
            temp.delete()
            throw IOException("Не удалось записать файл: $absolutePath")
        }
    }
}
