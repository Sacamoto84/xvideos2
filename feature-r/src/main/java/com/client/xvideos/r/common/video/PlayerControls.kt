package com.client.xvideos.r.common.video

/**
 * Интерфейс прямого управления воспроизведением видеоплеера в модуле RedGifs.
 *
 * Связывает внешние элементы управления (UI, жесты, кнопки) с экземпляром плеера ExoPlayer.
 */
interface PlayerControls {
    /** Перемотка вперед на заданное количество секунд. */
    fun forward(seconds: Float)

    /** Перемотка назад на заданное количество секунд. */
    fun rewind(seconds: Float)

    /** Переход к конкретной временной позиции в секундах. */
    fun seekTo(positionSeconds: Float)

    /** Полная остановка воспроизведения. */
    fun stop()

    /** Приостановка воспроизведения на паузу. */
    fun pause()

    /** Возобновление воспроизведения. */
    fun play()
}
